/**
 * Generate full CSV string mapping all 101 Food-101 classes
 */
export function generateFoodCaloriesCsv(): string {
  const headers = [
    'food_class',
    'display_name',
    'category',
    'calories_per_serving',
    'calories_per_100g',
    'serving_size_g',
    'protein_g',
    'carbs_g',
    'fat_g',
    'fiber_g',
    'usda_reference',
  ];

  const rows = FOOD_ITEMS_101.map((f) =>
    [
      f.id,
      `"${f.displayName}"`,
      `"${f.category}"`,
      f.caloriesPerServing,
      f.caloriesPer100g,
      f.servingSizeG,
      f.proteinG,
      f.carbsG,
      f.fatG,
      f.fiberG,
      `"${f.usdaReference}"`,
    ].join(',')
  );

  return [headers.join(','), ...rows].join('\n');
}

/**
 * Export class names list in canonical Food-101 order
 */
export function generateClassNamesJson(): string {
  return JSON.stringify(
    FOOD_ITEMS_101.map((f) => f.id),
    null,
    2
  );
}
